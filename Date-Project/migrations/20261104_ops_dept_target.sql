-- 目标库：Date-Project Python业务库。
-- 功能：财务中心「运营目标与人效」——汽配运营各部门年度目标、季度/月度分解与人效KPI（原 Excel「汽配运营26年目标汇总及人效管控」）。
-- 一行 = 一个年度 × 一个部门；合计、达成率、年度目标（季度之和）、实际人效等由后端计算，不存表。
-- 初始数据按 Excel 原值写入 2026 年；INSERT IGNORE 保证重复执行不会覆盖页面上已修改的值。金额单位：万元。

CREATE TABLE IF NOT EXISTS fin_ops_dept_target (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    target_year SMALLINT UNSIGNED NOT NULL COMMENT '目标年度，如 2026',
    dept_code VARCHAR(32) NOT NULL COMMENT '部门（如 US1、US2、US3&US5、EU、eBay）',
    sort_no INT NOT NULL DEFAULT 0 COMMENT '页面显示顺序',
    floor_target DECIMAL(14,4) NULL COMMENT '年度保底目标（万元）',
    sprint_target DECIMAL(14,4) NULL COMMENT '年度冲刺目标（万元）',
    actual_amount DECIMAL(14,4) NULL COMMENT '年度实际（万元，含退款），累计目标达成率 = 实际 ÷ 冲刺目标',
    new_product_target INT NULL COMMENT '新品数目标（个）',
    new_product_actual INT NULL COMMENT '新品实际上新（个）',
    target_margin_rate DECIMAL(8,4) NULL COMMENT '月均目标毛利率（小数，0.15 = 15%）',
    est_gross_profit DECIMAL(14,4) NULL COMMENT '全年预估毛利润（万元）',
    labor_cost_pack DECIMAL(14,4) NULL COMMENT '人力成本包（万元）',
    q1_target DECIMAL(14,4) NULL COMMENT 'Q1 目标（万元）',
    q2_target DECIMAL(14,4) NULL COMMENT 'Q2 目标（万元）',
    q3_target DECIMAL(14,4) NULL COMMENT 'Q3 目标（万元）',
    q4_target DECIMAL(14,4) NULL COMMENT 'Q4 目标（万元）',
    q1_actual DECIMAL(14,4) NULL COMMENT 'Q1 实际（万元）',
    q2_actual DECIMAL(14,4) NULL COMMENT 'Q2 实际（万元）',
    q3_actual DECIMAL(14,4) NULL COMMENT 'Q3 实际（万元）',
    q4_actual DECIMAL(14,4) NULL COMMENT 'Q4 实际（万元）',
    m01_target DECIMAL(14,4) NULL COMMENT '1月目标（万元）',
    m02_target DECIMAL(14,4) NULL COMMENT '2月目标（万元）',
    m03_target DECIMAL(14,4) NULL COMMENT '3月目标（万元）',
    m04_target DECIMAL(14,4) NULL COMMENT '4月目标（万元）',
    m05_target DECIMAL(14,4) NULL COMMENT '5月目标（万元）',
    m06_target DECIMAL(14,4) NULL COMMENT '6月目标（万元）',
    m07_target DECIMAL(14,4) NULL COMMENT '7月目标（万元）',
    m08_target DECIMAL(14,4) NULL COMMENT '8月目标（万元）',
    m09_target DECIMAL(14,4) NULL COMMENT '9月目标（万元）',
    m10_target DECIMAL(14,4) NULL COMMENT '10月目标（万元）',
    m11_target DECIMAL(14,4) NULL COMMENT '11月目标（万元）',
    m12_target DECIMAL(14,4) NULL COMMENT '12月目标（万元）',
    q1_efficiency_target DECIMAL(14,4) NULL COMMENT 'Q1 人效目标（万元/人）',
    q2_efficiency_target DECIMAL(14,4) NULL COMMENT 'Q2 人效目标（万元/人）',
    q3_efficiency_target DECIMAL(14,4) NULL COMMENT 'Q3 人效目标（万元/人）',
    q4_efficiency_target DECIMAL(14,4) NULL COMMENT 'Q4 人效目标（万元/人）',
    annual_efficiency_target DECIMAL(14,4) NULL COMMENT '年度人效目标（万元/人）',
    headcount INT NULL COMMENT '当前编制（人）',
    remark VARCHAR(500) NULL COMMENT '备注',
    updated_by VARCHAR(64) NULL COMMENT '最后修改人（ERP 用户名）',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_fin_ops_dept_target_year_dept (target_year, dept_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
COMMENT='汽配运营部门年度目标、季度/月度分解与人效KPI（手工维护）';

